"""Build docs/benchmarks/README.md and a comparison chart from the backends' result files.

uv run python -m bench.report
"""

import json
from pathlib import Path

OUT = Path(__file__).parent.parent / "docs" / "benchmarks"


def load() -> dict[str, dict]:
    return {
        backend: json.loads((OUT / f"{backend}.json").read_text())
        for backend in ("redis", "postgres")
        if (OUT / f"{backend}.json").exists()
    }


def chart(results: dict[str, dict]) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    styles = {"redis": ("tab:red", "o"), "postgres": ("tab:blue", "s")}
    for ax, seconds, title in zip(
        axes, (0.0, 0.05), ("0 ms jobs (pure coordination overhead)", "50 ms jobs"), strict=True
    ):
        for backend, r in results.items():
            rows = [t for t in r["throughput"] if t["job_seconds"] == seconds]
            color, marker = styles[backend]
            ax.plot(
                [t["workers"] for t in rows],
                [t["jobs_per_second"] for t in rows],
                marker=marker,
                color=color,
                label=f"{backend} queue",
            )
        if seconds:
            ws = [1, 2, 4, 8]
            ax.plot(ws, [w / seconds for w in ws], ":", color="grey", label="ideal")
        ax.set_title(title)
        ax.set_xlabel("workers")
        ax.set_ylabel("jobs / second")
        ax.set_xticks([1, 2, 4, 8])
        ax.grid(alpha=0.3)
        ax.legend()
    fig.tight_layout()
    fig.savefig(OUT / "throughput.png", dpi=120)


FINDINGS = """
## What the numbers say

1. **The queue isn't the bottleneck; Postgres is.** Both backends drain at almost the
   same rate, peak around 620 jobs/s with 4 workers on zero-work jobs, and fall off at 8.
   Every job costs two committing transactions (claim; fenced finish + effect) plus row
   locks on the source of truth. That's the price of the exactly-once-effects design,
   and it's the same whichever queue hands out the IDs.
2. **The jump from 1 to 2 workers looks super-linear because of the WAL flush.** One
   worker waits for every commit's disk flush in turn; concurrent workers' commits are
   flushed together (group commit). Confirmed by experiment: with
   `synchronous_commit = off`, one worker went from 201 to 607 jobs/s and 1 → 2 workers
   became ordinary sub-linear scaling (1.76×). (The setting was restored; durability
   isn't traded for a benchmark.)
3. **Real work scales linearly.** With 50 ms jobs, throughput doubles with each doubling
   of workers (14.8 → 29.3 → 60.2 → 119.7 jobs/s), about 75% of the ideal because each
   job also pays the coordination overhead.
4. **Redis wins on latency.** A blocking pop (`BLMPOP`) wakes the instant a job arrives;
   the Postgres backend has no blocking pop and polls with backoff, which shows up as
   queue wait: p50 7.6 vs 22.5 ms at 20 jobs/s. LISTEN/NOTIFY would let Postgres wake
   workers too.
5. **Recovery is the same** (≈ lease TTL + one monitor sweep): it's driven by leases,
   not by the queue.

**Verdict:** for this design a Postgres-only queue matches Redis on throughput and
removes a dual write (no ID to lose between commit and push), at the cost of ~15–25 ms
more queue wait. Redis earns its place for latency-sensitive work. Since leases still
live in Redis, going Postgres-only would also need leases in Postgres (or advisory
locks) before Redis could be dropped entirely.
"""


def pcts(d: dict) -> str:
    return " / ".join(str(d[p]) for p in ("50", "95", "99"))


def markdown(results: dict[str, dict]) -> str:
    backends = list(results)
    lines = [
        "# Benchmarks",
        "",
        "Generated by `uv run python -m bench.report` from the result files written by",
        "`make bench BACKEND=redis` and `make bench BACKEND=postgres`. Everything runs on one",
        "laptop (OrbStack containers sharing the CPU with Postgres and Redis), so absolute",
        "numbers are modest; the *shapes* and the comparison are the point.",
        "",
        "![throughput](throughput.png)",
        "",
        "## Throughput (pre-loaded backlog, drained by N workers)",
        "",
        "| job | workers | " + " | ".join(f"{b} jobs/s" for b in backends) + " |",
        "|---|---|" + "---|" * len(backends),
    ]
    first = results[backends[0]]["throughput"]
    for i, row in enumerate(first):
        cells = [str(results[b]["throughput"][i]["jobs_per_second"]) for b in backends]
        lines.append(
            f"| {row['job_seconds'] * 1000:.0f} ms | {row['workers']} | " + " | ".join(cells) + " |"
        )
    lines += [
        "",
        "## Latency under steady load (open-loop submitter, 4 workers, 50 ms jobs)",
        "",
        "| rate | backend | end-to-end p50 / p95 / p99 (ms) | queue wait p50 / p95 / p99 (ms) |",
        "|---|---|---|---|",
    ]
    for i, row in enumerate(results[backends[0]]["latency"]):
        for b in backends:
            r = results[b]["latency"][i]
            e2e, wait = r["end_to_end_ms"], r["queue_wait_ms"]
            lines.append(f"| {row['rate_per_second']}/s | {b} | {pcts(e2e)} | {pcts(wait)} |")
    lines += ["", "## Recovery (SIGKILL the worker running a job → another worker runs it)", ""]
    for b in backends:
        rec = results[b]["recovery"]
        lines.append(
            f"- **{b}**: median {rec['kill_to_rerun_seconds']['median']} s, "
            f"max {rec['kill_to_rerun_seconds']['max']} s over {rec['trials']} kills "
            f"(lease TTL {rec['lease_ttl_seconds']} s)"
        )
    return "\n".join(lines) + "\n" + FINDINGS


if __name__ == "__main__":
    results = load()
    chart(results)
    (OUT / "README.md").write_text(markdown(results))
    print(f"wrote {OUT / 'README.md'} and throughput.png for {list(results)}")
